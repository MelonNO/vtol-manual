// Generates sw-precache.js: the service worker's precache list and a content hash (WP09 R3; plan SW-02).
//   node scripts/gen-precache.mjs           write sw-precache.js
//   node scripts/gen-precache.mjs --check   exit 1 if sw-precache.js is not up to date (list or content hash)
// Plain Node, no packages. Run it after changing any file the field needs (pages, js, data, css, fonts, img, relay
// map, tools, icons, manifest): the hash changes, so browsers install a new worker and show the RELOAD toast.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync, realpathSync } from 'node:fs';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = 'sw-precache.js';

// What the field needs, as [directory, recursive, file test]. Paths are relative to the repo root (= SW scope).
const TEXT = new Set(['.html', '.js', '.css', '.svg', '.webmanifest', '.json']);
const RULES = [
  ['.', false, f => f.endsWith('.html') || f === 'manifest.webmanifest'],
  ['css', false, f => f.endsWith('.css')],
  ['fonts', false, f => f.endsWith('.woff2')],
  ['js', true, f => f.endsWith('.js')],
  ['data', false, f => f.endsWith('.js')],
  ['relay', false, f => f === 'map.html' || f.endsWith('.js')],          // the static map; not the retired Flask app
  ['relay/vendor', true, f => /\.(js|css|png)$/.test(f)],
  ['img', false, (f, dir) => /\.(webp|svg)$/.test(f) || (/\.(jpe?g|png)$/.test(f) && !existsSync(join(dir, f.replace(/\.\w+$/, '.webp'))))],
  ['img/diagrams', false, f => f.endsWith('.svg')],
  ['tools', false, f => f.endsWith('.html')],
  ['icons', false, f => f.endsWith('.png')]
];

function walk(rel, recursive, test, out) {
  const dir = join(ROOT, rel);
  if (!existsSync(dir)) return;
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name), r = rel === '.' ? name : rel + '/' + name;
    if (statSync(p).isDirectory()) { if (recursive) walk(r, true, test, out); }
    else if (test(name, dir)) out.push(r);
  }
}

// Sorted asset paths ('./' first), relative to the scope: './index.html', './js/common.js', …
export function listAssets() {
  const files = [];
  for (const [dir, rec, test] of RULES) walk(dir, rec, test, files);
  return ['./'].concat([...new Set(files)].sort().map(f => './' + f));
}

// SHA-256 over every listed file (path + content; text files with LF line endings, so any checkout gives the same hash).
export function contentHash(assets) {
  const h = createHash('sha256');
  for (const a of assets) {
    if (a === './') continue;
    const rel = a.slice(2), buf = readFileSync(join(ROOT, rel));
    h.update(rel + '\0');
    h.update(TEXT.has(extname(rel)) ? Buffer.from(buf.toString('utf8').replace(/\r\n/g, '\n'), 'utf8') : buf);
    h.update('\0');
  }
  return h.digest('hex').slice(0, 16);
}

export function render() {
  const assets = listAssets();
  return '// Generated by scripts/gen-precache.mjs — do not edit by hand.\n'
    + '// Regenerate after changing any listed file: node scripts/gen-precache.mjs  (check: --check)\n'
    + 'self.VTOL_PRECACHE = {\n'
    + "  hash: '" + contentHash(assets) + "',\n"
    + '  assets: [\n' + assets.map(a => "    '" + a + "'").join(',\n') + '\n  ]\n};\n';
}

function main() {
  const want = render(), file = join(ROOT, OUT);
  const cur = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (process.argv.includes('--check')) {
    if (cur === want) { console.log(OUT + ' up to date (' + (want.match(/^ {4}'/gm) || []).length + ' assets)'); return; }
    console.log('DIFF ' + OUT + ' is out of date. Run: node scripts/gen-precache.mjs');
    process.exit(1);
  }
  if (cur === want) { console.log(OUT + ' already up to date'); return; }
  writeFileSync(file, want);
  console.log('wrote ' + OUT);
}

// Run as a script (not when imported by the tests). realpath: Windows short (8.3) and long names compare equal.
const same = (a, b) => { try { return realpathSync(a).toLowerCase() === realpathSync(b).toLowerCase(); } catch (e) { return false; } };
if (process.argv[1] && same(fileURLToPath(import.meta.url), process.argv[1])) main();

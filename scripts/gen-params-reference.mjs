// Generates data/params-reference.js (global VtolParamsRef, contract C1.6) from the reference parameter file
// docs/reference/carrier-params-YYYY-MM-DD.param (a byte-exact copy of the carrier's Mission Planner export).
//   node scripts/gen-params-reference.mjs           write data/params-reference.js
//   node scripts/gen-params-reference.mjs --check   exit 1 if data/params-reference.js is not up to date
// Plain Node, no packages. The date comes from the file name. Exactly one reference file must exist; to update it,
// replace the file (new date in the name), re-run this script, then node scripts/gen-precache.mjs (docs/reference/README.md).
import { readFileSync, writeFileSync, readdirSync, existsSync, realpathSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

export const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
export const REF_DIR = 'docs/reference';
export const OUT = 'data/params-reference.js';
const FILE_RE = /^carrier-params-(\d{4}-\d{2}-\d{2})\.param$/;
const NAME_RE = /^[A-Z][A-Z0-9_]{0,15}$/;
const NUM_RE = /^[-+]?(\d+\.?\d*|\.\d+)([eE][-+]?\d+)?$/;

// The one reference file → { rel, savedDate }. Throws when there is none or more than one.
export function findReference() {
  const files = readdirSync(join(ROOT, REF_DIR)).filter(f => FILE_RE.test(f)).sort();
  if (files.length !== 1) throw new Error('expected exactly one ' + REF_DIR + '/carrier-params-YYYY-MM-DD.param, found ' + files.length + (files.length ? ': ' + files.join(', ') : ''));
  return { rel: REF_DIR + '/' + files[0], savedDate: files[0].match(FILE_RE)[1] };
}

// Strict parse of a Mission Planner "NAME,VALUE" file (CRLF or LF; '#' comments and blank lines allowed).
// Any other line, a bad name / number or a duplicate name is an error: the reference must be exact.
export function parseStrict(text) {
  const params = {}, errors = [];
  String(text).split(/\r?\n/).forEach((raw, i) => {
    const line = raw.replace(/#.*$/, '').trim();
    if (!line) return;
    const m = line.match(/^([^,\s]+)\s*,\s*(\S+)$/);
    if (!m || !NAME_RE.test(m[1]) || !NUM_RE.test(m[2])) { errors.push('line ' + (i + 1) + ': ' + raw.slice(0, 60)); return; }
    if (Object.prototype.hasOwnProperty.call(params, m[1])) { errors.push('line ' + (i + 1) + ': duplicate ' + m[1]); return; }
    params[m[1]] = Number(m[2]);
  });
  if (errors.length) throw new Error('reference parameter file is not clean:\n  ' + errors.slice(0, 10).join('\n  '));
  return params;
}

export function render() {
  const { rel, savedDate } = findReference();
  const buf = readFileSync(join(ROOT, rel));
  const params = parseStrict(buf.toString('utf8'));
  const names = Object.keys(params);
  const sha256 = createHash('sha256').update(buf).digest('hex');
  return '// Generated by scripts/gen-params-reference.mjs from ' + rel + ' — do not edit by hand.\n'
    + '// Regenerate after replacing the reference file: node scripts/gen-params-reference.mjs  (check: --check)\n'
    + '// Contract C1.6: VtolParamsRef = { source, savedDate, params: { NAME: number } } (+ count, sha256 of the file bytes).\n'
    + '(function (root, factory) {\n'
    + '  const api = factory();\n'
    + "  if (typeof module === 'object' && module.exports) module.exports = api;\n"
    + '  else root.VtolParamsRef = api;\n'
    + "})(typeof self !== 'undefined' ? self : this, function () {\n"
    + "  'use strict';\n"
    + '  return {\n'
    + "    source: '" + rel + "',\n"
    + "    savedDate: '" + savedDate + "',\n"
    + '    count: ' + names.length + ',\n'
    + "    sha256: '" + sha256 + "',\n"
    + '    params: {\n'
    + names.map(n => '      ' + n + ': ' + String(params[n])).join(',\n') + '\n'
    + '    }\n'
    + '  };\n'
    + '});\n';
}

function main() {
  let want;
  try { want = render(); } catch (e) { console.log('ERROR ' + e.message); process.exit(1); }
  const file = join(ROOT, OUT);
  const cur = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : null;
  if (process.argv.includes('--check')) {
    if (cur === want) { console.log(OUT + ' up to date (' + (want.match(/^ {6}[A-Z]/gm) || []).length + ' parameters)'); return; }
    console.log('DIFF ' + OUT + ' is out of date. Run: node scripts/gen-params-reference.mjs');
    process.exit(1);
  }
  if (cur === want) { console.log(OUT + ' already up to date'); return; }
  writeFileSync(file, want);
  console.log('wrote ' + OUT);
}

// Run as a script (not when imported by the tests). realpath: Windows short (8.3) and long names compare equal.
const same = (a, b) => { try { return realpathSync(a).toLowerCase() === realpathSync(b).toLowerCase(); } catch (e) { return false; } };
if (process.argv[1] && same(fileURLToPath(import.meta.url), process.argv[1])) main();

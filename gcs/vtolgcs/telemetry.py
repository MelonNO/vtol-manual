"""Client CRSF telemetry -> the C2 ``client`` object.

Frames arrive as ``crsf_fwd`` from the bridge and are decoded with the WP03
decoders (:mod:`vtolgcs.crsf`).  Two ages are kept:

* ``telemetry_age`` — since the last frame that comes **from the client**
  (flight mode, GPS, battery, attitude, vario, baro altitude).  Link statistics
  are generated by the TX module itself, so they do not prove the client is
  heard; the LQ value covers that.  This age drives the "FPV TELEMETRY LOST"
  alarm, which is the **primary** client-loss indicator: a real ELRS TX module
  may stop telemetry when its handset input stops, so ``!FS!`` may never arrive.
* per-group receive times, kept for the session log.
"""

from __future__ import annotations

import threading
import time
from dataclasses import dataclass
from typing import Any, Callable

from . import crsf
from .config import ClientConfig

#: Frame types that only the client (its flight controller) produces.
CLIENT_FRAME_TYPES = frozenset((crsf.FrameType.FLIGHT_MODE, crsf.FrameType.GPS, crsf.FrameType.BATTERY_SENSOR,
                                crsf.FrameType.ATTITUDE, crsf.FrameType.VARIO, crsf.FrameType.BARO_ALTITUDE))


@dataclass(frozen=True)
class TelemetryView:
    """Values the alarm rules need (``None`` = never received)."""

    age_s: float | None
    lq_pct: int | None
    cell_v: float | None
    sats: int | None
    failsafe: bool
    rth: bool
    rescue_not_ready: bool
    armed: bool | None


class ClientTelemetry:
    """Latest decoded client telemetry. Thread-safe."""

    def __init__(self, cfg: ClientConfig, clock: Callable[[], float] = time.perf_counter) -> None:
        self.cfg = cfg
        self._clock = clock
        self._lock = threading.Lock()
        self.link: crsf.LinkStatistics | None = None
        self.gps: crsf.Gps | None = None
        self.battery: crsf.Battery | None = None
        self.attitude: crsf.Attitude | None = None
        self.flight_mode: crsf.FlightModeStatus | None = None
        self.last_client_frame: float | None = None
        self.last_link_frame: float | None = None
        self.decode_errors = 0
        self.frames = 0

    def on_frame(self, frame: crsf.CrsfFrame, now: float | None = None) -> Any:
        """Decode one CRC-valid CRSF frame. Returns the decoded object (or ``None`` if not telemetry)."""
        now = self._clock() if now is None else now
        try:
            obj = crsf.decode_frame(frame)
        except crsf.CrsfError:
            with self._lock:
                self.decode_errors += 1
            return None
        with self._lock:
            self.frames += 1
            if isinstance(obj, crsf.LinkStatistics):
                self.link, self.last_link_frame = obj, now
            elif isinstance(obj, crsf.Gps):
                self.gps = obj
            elif isinstance(obj, crsf.Battery):
                self.battery = obj
            elif isinstance(obj, crsf.Attitude):
                self.attitude = obj
            elif isinstance(obj, crsf.FlightMode):
                self.flight_mode = obj.status
            if frame.type in CLIENT_FRAME_TYPES:
                self.last_client_frame = now
        return obj

    def age_s(self, now: float | None = None) -> float | None:
        now = self._clock() if now is None else now
        with self._lock:
            return None if self.last_client_frame is None else max(0.0, now - self.last_client_frame)

    def cell_voltage(self) -> float | None:
        with self._lock:
            batt = self.battery
        if batt is None or batt.voltage_v <= 0:
            return None
        return batt.voltage_v if self.cfg.report_cell_voltage else batt.voltage_v / self.cfg.cells

    def view(self, now: float | None = None) -> TelemetryView:
        now = self._clock() if now is None else now
        age = self.age_s(now)
        cell = self.cell_voltage()
        with self._lock:
            fm = self.flight_mode
            return TelemetryView(
                age_s=age, lq_pct=self.link.lq_pct if self.link else None, cell_v=cell,
                sats=self.gps.sats if self.gps else None,
                failsafe=bool(fm and fm.failsafe), rth=bool(fm and fm.rth),
                rescue_not_ready=bool(fm and fm.rescue_not_ready), armed=fm.armed if fm else None)

    def to_c2(self, now: float | None = None) -> dict[str, Any]:
        """The C2 ``client`` object (every key present; unknown values are ``None``)."""
        now = self._clock() if now is None else now
        age = self.age_s(now)
        with self._lock:
            ls, gps, batt, att, fm = self.link, self.gps, self.battery, self.attitude, self.flight_mode
        return {
            "profile_id": self.cfg.profile_id,
            "telemetry_age_ms": None if age is None else round(age * 1000),
            "link": {
                "rssi1_dbm": ls.rssi1_dbm if ls else None, "rssi2_dbm": ls.rssi2_dbm if ls else None,
                "lq_pct": ls.lq_pct if ls else None, "snr_db": ls.snr_db if ls else None,
                "rf_mode": ls.rf_mode if ls else None, "tx_power_mw": ls.tx_power_mw if ls else None,
                "dl_rssi_dbm": ls.dl_rssi_dbm if ls else None, "dl_lq_pct": ls.dl_lq_pct if ls else None,
                "dl_snr_db": ls.dl_snr_db if ls else None,
            },
            "gps": {
                "lat": gps.lat_deg if gps else None, "lon": gps.lon_deg if gps else None,
                "alt_m": gps.alt_m if gps else None, "gspd_kmh": gps.gspd_kmh if gps else None,
                "hdg_deg": gps.hdg_deg if gps else None, "sats": gps.sats if gps else None,
            },
            "battery": {
                "voltage_v": batt.voltage_v if batt else None, "current_a": batt.current_a if batt else None,
                "used_mah": batt.used_mah if batt else None, "remaining_pct": batt.remaining_pct if batt else None,
            },
            "attitude": {
                "pitch_rad": att.pitch_rad if att else None, "roll_rad": att.roll_rad if att else None,
                "yaw_rad": att.yaw_rad if att else None,
            },
            "flight_mode": {
                "raw": fm.raw.split("\0", 1)[0] if fm else None, "failsafe": fm.failsafe if fm else None,
                "armed": fm.armed if fm else None, "rescue_not_ready": fm.rescue_not_ready if fm else None,
            },
        }


def describe(obj: Any) -> dict[str, Any] | None:
    """Session-log form of a decoded telemetry object: ``{"kind": ..., <fields>}``."""
    kinds = {crsf.LinkStatistics: "link", crsf.Gps: "gps", crsf.Battery: "battery", crsf.Attitude: "attitude",
             crsf.FlightMode: "flight_mode", crsf.Vario: "vario", crsf.BaroAltitude: "baro"}
    kind = kinds.get(type(obj))
    if kind is None:
        return None
    if isinstance(obj, crsf.FlightMode):
        st = obj.status
        return {"kind": kind, "raw": obj.text, "failsafe": st.failsafe, "armed": st.armed,
                "rescue_not_ready": st.rescue_not_ready}
    data = {k: v for k, v in vars(obj).items()}
    if isinstance(obj, crsf.LinkStatistics):
        data["tx_power_mw"] = obj.tx_power_mw
    return {"kind": kind, **data}
